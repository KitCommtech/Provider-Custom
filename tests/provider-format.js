'use strict';
const assert=require('node:assert/strict'),f=require('../daloradius/app/operators/static/js/provider-format.js');
assert.equal(f.timeoutSeconds('90','60'),'5400');
assert.equal(f.timeoutSeconds('2','3600'),'7200');
assert.equal(f.timeoutSeconds('61','1'),'61');
assert.equal(f.timeoutSeconds('','60'),'');
for(const [value,unit] of [['1.5','3600'],['-1','60'],['0','60'],['8761','3600'],['1','100']])assert.throws(()=>f.timeoutSeconds(value,unit));
assert.equal(f.duration('5400'),'1h 30m');
assert.equal(f.duration(3661),'1h 1m 1s');
assert.equal(f.duration(3600),'1h');
assert.equal(f.duration(0),'0s');
assert.equal(f.duration(null),'—');
assert.equal(f.duration('bad'),'—');
assert.deepEqual(f.dateTime('2026-10-28 13:04:09'),{date:'28 Oct 2026',time:'13:04:09'});
assert.equal(f.dateTimeText('2026-10-10 19:25:25.255725'),'10 Oct 2026 · 19:25:25');
assert.equal(f.dateTimeText('2026-10-28 13:04:09'),'28 Oct 2026 · 13:04:09');
for(const value of [null,'0000-00-00 00:00:00','2026-02-30 13:04:09','2026-10-28 25:00:00','<script>'])assert.equal(f.dateTime(value),null);
assert.equal(f.details('{"deleted":{"admin":2}}'),'{\n  "deleted": {\n    "admin": 2\n  }\n}');
console.log('24 formatting and conversion checks passed.');
